import { CurrencyCode, CurrencyConfig, LanguageCode } from '../types';

export const CURRENCY_CONFIGS: Record<CurrencyCode, CurrencyConfig> = {
  USD: { code: 'USD', symbol: '$', rate: 1.0, locale: 'en-US' },
  EUR: { code: 'EUR', symbol: '€', rate: 0.92, locale: 'de-DE' },
  GBP: { code: 'GBP', symbol: '£', rate: 0.78, locale: 'en-GB' },
  JPY: { code: 'JPY', symbol: '¥', rate: 152.0, locale: 'ja-JP' },
  CAD: { code: 'CAD', symbol: 'CA$', rate: 1.36, locale: 'en-CA' },
  AUD: { code: 'AUD', symbol: 'AU$', rate: 1.52, locale: 'en-AU' },
  CHF: { code: 'CHF', symbol: 'CHF', rate: 0.88, locale: 'de-CH' },
};

export const formatCurrency = (amountUSD: number, currency: CurrencyCode): string => {
  const config = CURRENCY_CONFIGS[currency] || CURRENCY_CONFIGS.USD;
  const converted = amountUSD * config.rate;
  
  if (currency === 'JPY') {
    return `${config.symbol}${Math.round(converted).toLocaleString(config.locale)}`;
  }
  return `${config.symbol}${converted.toLocaleString(config.locale, {
    minimumFractionDigits: 2,
    maximumFractionDigits: 2,
  })}`;
};

